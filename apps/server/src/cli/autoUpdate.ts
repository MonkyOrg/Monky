/**
 * One updater for the whole machine. The CLI is a global package shared by
 * every server, so per-server updaters raced each other installing it, and
 * only the first one restarted its own server onto the new code.
 */
export const AUTO_UPDATER_PROCESS_NAME = 'monky-auto-updater';
export const MAX_AUTO_UPDATE_INTERVAL_HOURS = 168;
export const DEFAULT_AUTO_UPDATE_TIME = '04:00';
const DEFAULT_AUTO_UPDATE_INTERVAL_HOURS = 2;

export type AutoUpdateSchedule =
  | { type: 'daily'; time: string }
  | { type: 'interval'; hours: number };

/** `HH:MM` in 24-hour time, normalized to two-digit hours. */
export function parseDailyTime(value: string): string {
  const match = /^(\d{1,2}):(\d{2})$/.exec(value.trim());
  if (!match || Number(match[1]) > 23 || Number(match[2]) > 59) {
    throw new Error(t('config.invalidDailyTime', { value }));
  }
  return `${match[1].padStart(2, '0')}:${match[2]}`;
}

/** Whole hours between 1 and one week. */
export function parseIntervalHours(value: string): number {
  const hours = Number(value.trim());
  if (!/^\d+$/.test(value.trim()) || !Number.isSafeInteger(hours) || hours < 1 || hours > MAX_AUTO_UPDATE_INTERVAL_HOURS) {
    throw new Error(t('config.invalidIntervalHours', { value, max: MAX_AUTO_UPDATE_INTERVAL_HOURS }));
  }
  return hours;
}

export function getAutoUpdaterScriptPath(): string {
  return path.join(getRegistryDir(), 'auto-update.cjs');
}

/**
 * Daemon run by PM2: waits for the schedule, then runs `monky update --yes`,
 * which installs the package once and restarts every server that is running.
 *
 * Node fires any `setTimeout` above 2^31-1 ms at once, which turned a long
 * interval into a tight loop, so long waits are split; the schedule is also
 * re-validated here in case the file is edited by hand.
 */
export function generateUpdaterScript(options: { cliEntry: string; beta: boolean; schedule: AutoUpdateSchedule }): string {
  const args = [options.cliEntry, 'update', '--yes'];
  if (options.beta) args.push('--beta');

  return `// Monky auto-updater daemon — generated by "monky config set autoUpdate".
// Do not edit: this file is rewritten whenever auto-update is reconfigured.
const { spawnSync } = require('child_process');

const args = ${JSON.stringify(args, null, 2)};
const schedule = ${JSON.stringify(options.schedule)};
const MAX_TIMER_MS = 2147483647;
const MAX_INTERVAL_HOURS = ${MAX_AUTO_UPDATE_INTERVAL_HOURS};

function nextRunAt(now) {
  if (schedule.type === 'interval') {
    const hours = Math.min(MAX_INTERVAL_HOURS, Math.max(1, Math.floor(Number(schedule.hours)) || 24));
    return now + hours * 60 * 60 * 1000;
  }
  const match = /^(\\d{1,2}):(\\d{2})$/.exec(String(schedule.time));
  const hour = match && Number(match[1]) <= 23 ? Number(match[1]) : 4;
  const minute = match && Number(match[2]) <= 59 ? Number(match[2]) : 0;
  const next = new Date(now);
  next.setHours(hour, minute, 0, 0);
  if (next.getTime() <= now) next.setDate(next.getDate() + 1);
  return next.getTime();
}

function runUpdateCheck() {
  console.log('[' + new Date().toISOString() + '] [monky-updater] Checking scheduled updates...');
  try {
    const result = spawnSync(process.execPath, args, { stdio: 'inherit' });
    console.log('[monky-updater] Check finished with code:', result.status);
  } catch (err) {
    console.error('[monky-updater] Error while running update check:', err);
  }
  scheduleNext();
}

function waitUntil(due) {
  const remaining = due - Date.now();
  if (remaining <= 0) {
    runUpdateCheck();
    return;
  }
  setTimeout(() => waitUntil(due), Math.min(remaining, MAX_TIMER_MS));
}

function scheduleNext() {
  const due = nextRunAt(Date.now());
  console.log('[' + new Date().toISOString() + '] [monky-updater] Next check scheduled for:', new Date(due).toLocaleString());
  waitUntil(due);
}

console.log('[monky-updater] Automatic update daemon started (' + JSON.stringify(schedule) + ').');
scheduleNext();
`;
}

/** The machine updater, per-server updaters from older versions and the pre-registry one. */
export function isUpdaterProcessName(name: string | undefined): boolean {
  return name === AUTO_UPDATER_PROCESS_NAME || name === LEGACY_UPDATER_PROCESS_NAME ||
    Boolean(name?.startsWith(`${UPDATER_PROCESS_PREFIX}-`));
}

export function isAutoUpdateEnabled(): boolean {
  return listPm2Processes().some((entry) => isUpdaterProcessName(entry.name));
}

function removeUpdaterProcesses(): void {
  for (const entry of listPm2Processes()) {
    if (entry.name && isUpdaterProcessName(entry.name)) {
      runSync('pm2', ['delete', entry.name], { stdio: 'ignore' });
    }
  }
}

/** Scripts the per-server updaters of older versions left in each data directory. */
function removePerServerUpdaterScripts(): void {
  for (const server of listServers()) {
    for (const name of ['auto-update.cjs', 'auto-update.sh']) {
      try {
        fs.rmSync(path.join(server.dataDir, name), { force: true });
      } catch {
        // A leftover script is harmless once its PM2 process is gone.
      }
    }
  }
}

function describeSchedule(schedule: AutoUpdateSchedule): string {
  return schedule.type === 'interval'
    ? t('update.scheduleEvery', { value: schedule.hours })
    : t('update.scheduleDaily', { value: schedule.time });
}

export async function enableAutoUpdate(schedule: AutoUpdateSchedule): Promise<void> {
  ensurePm2();

  const scriptPath = getAutoUpdaterScriptPath();
  const beta = parseSemver(getLocalVersion()).isBeta;
  await fs.promises.mkdir(path.dirname(scriptPath), { recursive: true });
  await fs.promises.writeFile(
    scriptPath,
    generateUpdaterScript({ cliEntry: getCliEntryPath(), beta, schedule }),
    { encoding: 'utf8', mode: 0o600 }
  );

  removeUpdaterProcesses();
  removePerServerUpdaterScripts();

  const interpreter = resolveInterpreter();
  const result = runSync(
    'pm2',
    [
      'start',
      scriptPath,
      '--name',
      AUTO_UPDATER_PROCESS_NAME,
      // Same reason as the server's ecosystem file: a bare `node` is resolved
      // from the PM2 daemon's environment, which keeps the Node it was started
      // with. After a Node upgrade that path can be gone, and PM2 then fails to
      // spawn while still reporting the process as online (#522).
      ...(interpreter ? ['--interpreter', interpreter] : []),
    ],
    { stdio: 'inherit' }
  );
  if (result.error || result.status !== 0) {
    throw new Error(t('update.autoUpdateFailed'));
  }

  runSync('pm2', ['save'], { stdio: 'ignore' });

  console.log(color(t('update.autoUpdateEnabled'), ANSI.green));
  console.log(t('update.schedule', { schedule: describeSchedule(schedule) }));
  console.log(beta ? t('update.channelBeta') : t('update.channelStable'));
  console.log(t('update.autoUpdateScope'));
  console.log(t('update.script', { path: scriptPath }));
  console.log(color(t('update.disableHint'), ANSI.dim));
}

export async function disableAutoUpdate(): Promise<void> {
  if (!isPm2Available()) {
    console.log(color(t('update.pm2NotFound'), ANSI.yellow));
    return;
  }

  removeUpdaterProcesses();
  runSync('pm2', ['save'], { stdio: 'ignore' });
  fs.rmSync(getAutoUpdaterScriptPath(), { force: true });
  removePerServerUpdaterScripts();
  console.log(color(t('update.autoUpdateDisabled'), ANSI.green));
}

async function askUntilValid<T>(question: string, defaultValue: string, parse: (value: string) => T): Promise<T> {
  while (true) {
    const answer = await ask(question, defaultValue);
    try {
      return parse(answer);
    } catch (error) {
      if (error instanceof PromptCancelledError) throw error;
      console.log(color(error instanceof Error ? error.message : String(error), ANSI.yellow));
    }
  }
}

/** Interactive schedule choice; scripts keep the daily default. */
export async function askAutoUpdateSchedule(): Promise<AutoUpdateSchedule> {
  if (!process.stdin.isTTY) return { type: 'daily', time: DEFAULT_AUTO_UPDATE_TIME };
  const dailyOption = t('config.autoUpdateDaily');
  const intervalOption = t('config.autoUpdateInterval');
  const mode = await askChoice(t('config.autoUpdateScheduleType'), [dailyOption, intervalOption]);
  if (mode === intervalOption) {
    const hours = await askUntilValid(
      t('config.autoUpdateHoursInterval', { max: MAX_AUTO_UPDATE_INTERVAL_HOURS }),
      String(DEFAULT_AUTO_UPDATE_INTERVAL_HOURS),
      parseIntervalHours
    );
    return { type: 'interval', hours };
  }
  return { type: 'daily', time: await askUntilValid(t('config.autoUpdateDailyTime'), DEFAULT_AUTO_UPDATE_TIME, parseDailyTime) };
}

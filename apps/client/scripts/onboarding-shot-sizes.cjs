/**
 * Writes the pixel size of every onboarding screenshot so the guide can give
 * each <img> its width and height before the file loads. Without them the
 * card is measured without the picture and grows once it arrives.
 *
 *   node scripts/onboarding-shot-sizes.cjs          rewrite the list
 *   node scripts/onboarding-shot-sizes.cjs --check  fail if it is stale
 *
 * `npm run screenshots:onboarding` runs it after capturing.
 */
const fs = require('node:fs');
const path = require('node:path');

const clientRoot = path.resolve(__dirname, '..');
const shotsDir = path.join(clientRoot, 'src', 'renderer', 'assets', 'onboarding');
const target = path.join(clientRoot, 'src', 'renderer', 'views', 'onboardingShotSizes.ts');

function pngSize(file) {
  const header = Buffer.alloc(24);
  const handle = fs.openSync(file, 'r');
  try {
    fs.readSync(handle, header, 0, header.length, 0);
  } finally {
    fs.closeSync(handle);
  }
  if (header.readUInt32BE(0) !== 0x89504e47 || header.toString('ascii', 12, 16) !== 'IHDR') {
    throw new Error(`${path.basename(file)} is not a PNG`);
  }
  return [header.readUInt32BE(16), header.readUInt32BE(20)];
}

function renderShotSizes() {
  const entries = fs.readdirSync(shotsDir)
    .filter((name) => name.endsWith('.png'))
    .sort()
    .map((name) => {
      const [width, height] = pngSize(path.join(shotsDir, name));
      return `  '${name.slice(0, -4)}': [${width}, ${height}],`;
    });
  return [
    '// Generated by scripts/onboarding-shot-sizes.cjs from the PNG headers. Do not edit.',
    'export const ONBOARDING_SHOT_SIZES: Readonly<Record<string, readonly [number, number]>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

module.exports = { pngSize, renderShotSizes, target };

if (require.main === module) {
  const expected = renderShotSizes();
  // Windows checkouts may convert the file to CRLF; the content is what matters.
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (current !== expected) {
      console.error(`${path.relative(clientRoot, target)} is stale: run node scripts/onboarding-shot-sizes.cjs`);
      process.exit(1);
    }
  } else if (current !== expected) {
    fs.writeFileSync(target, expected);
    console.log(`  ${path.relative(clientRoot, target)}`);
  }
}

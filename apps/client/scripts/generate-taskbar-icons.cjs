/**
 * Regenerates src/main/taskbarCallIcons.ts, the masks behind the call buttons
 * on the Windows taskbar thumbnail.
 *
 * The glyphs come from the Material Symbols font the app's own voice controls
 * use (the `material-symbols` dependency, Apache License 2.0). Each is drawn
 * white at optical size 20, the size the app's ~18 px icons get, and scaled up
 * to a 64 px canvas; the main process then resizes and tints it for the screen
 * scale and the taskbar theme.
 *
 * Usage, from apps/client: node scripts/generate-taskbar-icons.cjs
 */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const GLYPHS = ['mic', 'mic_off', 'headphones', 'headset_off', 'call_end'];
const MASK_SIZE = 64;
const OPTICAL_SIZE = 20;
const output = path.resolve(__dirname, '..', 'src', 'main', 'taskbarCallIcons.ts');

if (!process.versions.electron) {
  const env = { ...process.env };
  delete env.ELECTRON_RUN_AS_NODE;
  const result = spawnSync(require('electron'), [__filename], { env, stdio: 'inherit' });
  process.exit(result.status ?? 1);
}

const { app, BrowserWindow } = require('electron');

app.whenReady().then(async () => {
  const font = fs.readFileSync(require.resolve('material-symbols/material-symbols-outlined.woff2'));
  const window = new BrowserWindow({ show: false, webPreferences: { offscreen: true } });
  await window.loadURL('data:text/html,<!doctype html><title>taskbar icons</title>');
  const masks = await window.webContents.executeJavaScript(
    `(${renderMasks})(${JSON.stringify(font.toString('base64'))}, ${JSON.stringify(GLYPHS)}, ${MASK_SIZE}, ${OPTICAL_SIZE})`,
  );
  window.destroy();
  const entries = GLYPHS.map((glyph) => `  ${glyph}:\n    '${masks[glyph]}',`).join('\n');
  fs.writeFileSync(output, `// Generated by scripts/generate-taskbar-icons.cjs: run it again instead of editing.
// Material Symbols Outlined glyphs (Apache License 2.0), white on transparent,
// optical size ${OPTICAL_SIZE}, ${MASK_SIZE}x${MASK_SIZE} px PNG.
export const TASKBAR_ICON_MASKS = {
${entries}
} as const;

export type TaskbarGlyph = keyof typeof TASKBAR_ICON_MASKS;
`);
  console.log(`Wrote ${path.relative(process.cwd(), output)}`);
  app.exit(0);
}).catch((error) => {
  console.error(error);
  app.exit(1);
});

async function renderMasks(fontBase64, glyphs, size, opticalSize) {
  const bytes = Uint8Array.from(atob(fontBase64), (character) => character.charCodeAt(0));
  document.fonts.add(await new FontFace('Material Symbols Outlined', bytes.buffer).load());
  const masks = {};
  for (const glyph of glyphs) {
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = size;
    const context = canvas.getContext('2d');
    // Chromium takes the optical size from the declared font size, so the glyph
    // is set at that size and the canvas is scaled instead.
    context.scale(size / opticalSize, size / opticalSize);
    context.fillStyle = '#fff';
    context.font = `${opticalSize}px 'Material Symbols Outlined'`;
    // The glyph fills the em square above the baseline.
    context.fillText(glyph, 0, opticalSize);
    const pixels = context.getImageData(0, 0, size, size).data;
    let ink = false;
    for (let index = 0; index < size * size; index++) {
      if (pixels[index * 4 + 3] === 0) continue;
      ink = true;
      const x = index % size;
      const y = Math.floor(index / size);
      if (x === 0 || y === 0 || x === size - 1 || y === size - 1) throw new Error(`${glyph} touches the canvas edge`);
    }
    // A missing ligature would render the glyph name as text instead.
    if (!ink || context.measureText(glyph).width !== opticalSize) throw new Error(`${glyph} is not a Material Symbols glyph`);
    masks[glyph] = canvas.toDataURL('image/png').slice('data:image/png;base64,'.length);
  }
  return masks;
}
